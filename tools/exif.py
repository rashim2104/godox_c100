"""EXIF APP1 segment for exif_cave.s, as an assembler include.

    python3 -I tools/exif.py asm > build/obj/exif.inc

Little-endian TIFF with IFD0 (resolution, make, model, software, date,
artist) and an Exif IFD (version, the dates, their UTC offsets, colour space,
pixel size). Per photo, the camera fills in the three dates (DateTime,
DateTimeOriginal, CreateDate: DATE0..2) and the pixel size (W, H); their
offsets in APP1 come out as equs. No value is shared between tags
(exiftool -validate flags overlaps), and it passes with no warnings.
Settings from the environment: EXIF_MAKE, EXIF_MODEL, EXIF_SOFTWARE,
EXIF_ARTIST, EXIF_OFFSET (the camera has no time zone, so it is fixed here).
"""
import os, struct, sys

ASCII, SHORT, LONG, RATIONAL, UNDEFINED = 2, 3, 4, 5, 7
SIZE = {ASCII: 1, SHORT: 2, LONG: 4, RATIONAL: 8, UNDEFINED: 1}
DATE_LEN = 20  # "YYYY:MM:DD HH:MM:SS\0"


def cfg():
    return {
        'make': os.environ.get('EXIF_MAKE', 'Godox'),
        'model': os.environ.get('EXIF_MODEL', 'C100'),
        'software': os.environ.get('EXIF_SOFTWARE', 'C100-V1.1.6'),
        'artist': os.environ.get('EXIF_ARTIST', 'Rashim'),
        'offset': os.environ.get('EXIF_OFFSET', '+05:30'),
    }


def build(c=None, width=0, height=0, date=b'    :  :     :  :  '):
    """Returns (app1 bytes, {name: offset in app1}). TIFF offsets are from 'II'."""
    c = c or cfg()
    asc = lambda s: s.encode('ascii') + b'\0'
    date = date.ljust(DATE_LEN - 1)[:DATE_LEN - 1] + b'\0'

    ifd0 = [
        (0x010f, ASCII, None, None, asc(c['make'])),
        (0x0110, ASCII, None, None, asc(c['model'])),
        (0x011a, RATIONAL, 1, None, struct.pack('<II', 72, 1)),
        (0x011b, RATIONAL, 1, None, struct.pack('<II', 72, 1)),
        (0x0128, SHORT, 1, None, struct.pack('<H', 2)),
        (0x0131, ASCII, None, None, asc(c['software'])),
        (0x0132, ASCII, None, 'DATE0', date),
        (0x013b, ASCII, None, None, asc(c['artist'])),
        (0x0213, SHORT, 1, None, struct.pack('<H', 1)),
        (0x8769, LONG, 1, 'EXIF_IFD', b'\0' * 4),
    ]
    exif = [
        (0x9000, UNDEFINED, 4, None, b'0232'),
        (0x9003, ASCII, None, 'DATE1', date),
        (0x9004, ASCII, None, 'DATE2', date),
        (0x9010, ASCII, None, None, asc(c['offset'])),
        (0x9011, ASCII, None, None, asc(c['offset'])),
        (0x9012, ASCII, None, None, asc(c['offset'])),
        (0x9101, UNDEFINED, 4, None, bytes([1, 2, 3, 0])),
        (0xa001, SHORT, 1, None, struct.pack('<H', 1)),
        (0xa002, LONG, 1, 'W', struct.pack('<I', width)),
        (0xa003, LONG, 1, 'H', struct.pack('<I', height)),
    ]
    ifd_len = lambda ifd: 2 + 12 * len(ifd) + 4
    ifd0_at = 8
    exif_at = ifd0_at + ifd_len(ifd0)
    data_at = exif_at + ifd_len(exif)

    tiff = bytearray(b'II*\0' + struct.pack('<I', ifd0_at))
    data = bytearray()
    where = {}  # name -> TIFF offset of the value

    def value_at(value):
        if len(data) % 2:
            data.append(0)
        data.extend(value)
        return data_at + len(data) - len(value)

    def emit(ifd, next_ifd=0):
        out = bytearray(struct.pack('<H', len(ifd)))
        for tag, typ, count, name, value in sorted(ifd):
            count = count or len(value) // SIZE[typ]
            entry_at = len(tiff) + len(out)
            if len(value) <= 4:
                field = value.ljust(4, b'\0')
                if name:
                    where[name] = entry_at + 8
            else:
                off = value_at(value)
                if name:
                    where[name] = off
                field = struct.pack('<I', off)
            out += struct.pack('<HHI', tag, typ, count) + field
        out += struct.pack('<I', next_ifd)
        tiff.extend(out)

    emit(ifd0)
    struct.pack_into('<I', tiff, where.pop('EXIF_IFD'), exif_at)
    emit(exif)
    assert len(tiff) == data_at
    tiff += data

    body = b'Exif\0\0' + tiff
    app1 = b'\xff\xe1' + struct.pack('>H', 2 + len(body)) + body
    head = 4 + 6  # FFE1, length, "Exif\0\0"
    return app1, {k: head + v for k, v in where.items()}


def asm():
    app1, where = build()
    pad = (-len(app1)) % 4
    lines = ['@ generated by tools/exif.py, do not edit',
             f'    .equ    APP1_LEN, {len(app1)}']
    lines += [f'    .equ    {k}, {v}' for k, v in sorted(where.items())]
    lines += ['    .balign 4', 'APP1:']
    blob = app1 + b'\0' * pad
    for i in range(0, len(blob), 16):
        lines.append('    .byte   ' + ', '.join(f'0x{b:02x}' for b in blob[i:i + 16]))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    if sys.argv[1:] == ['asm']:
        sys.stdout.write(asm())
    else:
        sys.exit(__doc__)
